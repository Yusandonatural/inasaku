def cell(v, m):
    if v == 0:
        return '<td style="color:#a9b4ac">—</td>'
    col = "#2e8b57" if v >= 4 else ("#a8533a" if v <= 2 else "")
    st = ' style="color:%s;font-weight:600"' % col if col else ""
    return "<td%s>%s</td>" % (st, m[v])


